/**
 * 同一個使用者的寫入排隊（2026-10-11 壓測 races 抓到的三個「先檢查、再寫入」競態）：
 * - 配額：先 count 再 insert，並發 10 個建立全部成功（FREE 上限 3）。
 * - 超賣：先重放帳本確認持股夠再寫入，持有 1,000 股時並發 5 筆賣 1,000，成功 3 筆，持股變成 −2,000。
 * - 重複匯入：先查 externalRef 再寫入，並發 5 次各自發一個 importId，大多指向 0 筆、撤銷只會 404。
 *
 * 檢查要重放帳本、還會呼叫上游，塞不進同一個 DB 交易；所以改成**以使用者為單位排隊**：拿到鎖才檢查，
 * 寫完、回應送出才放。不同使用者互不影響。
 */
export interface UserWriteLockPort {
  /** 等到這個使用者的寫入鎖，回傳釋放函式（可重複呼叫，只有第一次有作用）。 */
  acquire(firebaseUid: string): Promise<() => Promise<void>>;
}
